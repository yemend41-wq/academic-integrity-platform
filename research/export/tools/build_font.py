"""Generate a self-contained, subset DejaVu Type 0 PDF font and its shaping tables."""
import base64
import io
import json
import pathlib
import re
import unicodedata as u
import zlib
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
path = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
font = TTFont(path, recalcTimestamp=False)
ranges = [(32, 0x24F), (0x300, 0x36f), (0x600, 0x6ff), (0x750, 0x77f),
          (0x8a0, 0x8ff), (0x2000, 0x206f), (0x20ac, 0x20ac), (0x2190, 0x2199),
          (0xfb50, 0xfdff), (0xfe70, 0xfeff), (0xfffd, 0xfffd)]
chars = [c for a,b in ranges for c in range(a, b + 1)]
opts = subset.Options()
opts.hinting = False
opts.recalc_timestamp = False
ss = subset.Subsetter(options=opts)
ss.populate(unicodes=chars)
ss.subset(font)
cmap = font.getBestCmap()
glyphs = {c:font.getGlyphID(g) for c,g in cmap.items()}
widths = [font['hmtx'][g][0] for g in font.getGlyphOrder()]
forms = {}
lam = {}
for c in cmap:
    fields = u.decomposition(chr(c)).split()
    if not fields or fields[0] not in ('<initial>', '<medial>', '<final>', '<isolated>'):
        continue
    form = {'<isolated>':0, '<final>':1,'<initial>':2,'<medial>':3}[fields[0]]
    if len(fields) == 2:
        original = int(fields[1],16)
        forms.setdefault(original,[original]*4)[form] = c
    elif len(fields) == 3 and fields[1] == '0644' and int(fields[2],16) in (0x622,0x623,0x625,0x627):
        original = int(fields[2],16)
        lam.setdefault(original,[0,0])[form] = c
joining = {}
for row in pathlib.Path('/usr/share/unicode/extracted/DerivedJoiningType.txt').read_text().splitlines():
    entry = row.split('#')[0].strip()
    if not entry: continue
    key, value = [s.strip() for s in entry.split(';')]
    if '..' in key: lo,hi = key.split('..')
    else: lo=hi=key
    for c in range(int(lo,16),int(hi,16)+1):
        if c in cmap or c in (0x200c,0x200d):
            joining[c] = value
base_anchors = {}
mark_anchors = {}
for lookup in font['GPOS'].table.LookupList.Lookup:
    if lookup.LookupType != 4: continue
    for sub in lookup.SubTable:
        if not any(m in sub.MarkCoverage.glyphs for c,m in cmap.items() if 0x64b <= c <= 0x65f): continue
        for name, rec in zip(sub.MarkCoverage.glyphs, sub.MarkArray.MarkRecord):
            anc = rec.MarkAnchor
            mark_anchors[font.getGlyphID(name)] = [anc.XCoordinate,anc.YCoordinate]
        for name, rec in zip(sub.BaseCoverage.glyphs, sub.BaseArray.BaseRecord):
            anc = rec.BaseAnchor[0]
            if anc: base_anchors[font.getGlyphID(name)] = [anc.XCoordinate, anc.YCoordinate]
# Shaping was materialized above; the PDF viewer only needs outlines and metrics.
for tag in ['GPOS','GSUB','GDEF','MATH','kern']:
    if tag in font: del font[tag]
bio = io.BytesIO()
font.save(bio)
raw = bio.getvalue()
data = dict(upm=font['head'].unitsPerEm, cmap=glyphs, widths=widths, forms=forms,
            joining=joining, lam=lam, baseAnchors=base_anchors, markAnchors=mark_anchors,
            rawLength=len(raw), font=base64.b64encode(zlib.compress(raw,9)).decode())
(ROOT/'vendor'/'font.mjs').write_text(
    '// Generated by tools/build_font.py from DejaVu Sans. See font-LICENSE.txt.\nexport default '+
    json.dumps(data, separators=(',',':'))+';\n')
