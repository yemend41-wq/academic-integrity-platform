"""Fit bilingual LSA to document-disjoint Universal Dependencies PUD sentence pairs."""
import base64
import hashlib
import json
import re
import unicodedata
from collections import defaultdict
from pathlib import Path
import numpy as np
from sklearn.decomposition import TruncatedSVD
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.preprocessing import normalize

ROOT = Path(__file__).resolve().parent
STOP = set("""the a an that these those for on and or of in at is was am are be been but by has have had he she his her its it with which who we they this from to as their than there are i my both not can will would you our us into they were also more if after before about all did does do same 
في من بين او عن علي الي التي الذي الذين اللاتي هذا هذه ذلك تلك وهو وهي مع ما ان كان كانت يكون لم لن له لها قد هو هي هم هن و ثم كما حتي فقد وقد لقد عند مثل كل بعض بعد قبل دون اذا اذ لكن انما""".split())

def norm(word):
    w = ''.join(c for c in unicodedata.normalize('NFKD', word.lower()) if not unicodedata.combining(c))
    return w.replace('ى','ي').replace('ـ','')

def words(t):
    return [w for w in map(norm, re.findall(r"[^\W_]+",t, re.UNICODE)) if w not in STOP and len(w)>1]

def group(k):
    return k[:-3]

pairs = [json.loads(line) for line in (ROOT/'parallel.jsonl').read_text().splitlines()]
# Assign all sentences from a source document to the same split.
held = lambda p: int(hashlib.sha256(group(p[0]).encode()).hexdigest()[:8], 16) % 5 == 0
train = [p for p in pairs if not held(p)]
test = [p for p in pairs if held(p)]
assert set(group(p[0]) for p in train).isdisjoint(group(p[0]) for p in test)
vec = TfidfVectorizer(tokenizer=words, token_pattern=None, lowercase=False,sublinear_tf=True,min_df=2)
matrix = vec.fit_transform([en + ' ' + ar for _,en,ar in train])
model = TruncatedSVD(n_components=48,algorithm='randomized',random_state=183,n_iter=8).fit(matrix)
weights = normalize(model.components_.T.copy())
vocab = vec.get_feature_names_out().tolist()
quantized = np.rint(weights * 127).astype(np.int8)
vocab_index = {w:i for i,w in enumerate(vocab)}
def encode(s):
    ids = [vocab_index[w] for w in words(s) if w in vocab_index]
    if not ids: return np.zeros(48)
    v = quantized[ids].sum(axis=0).astype(float)
    return v/max(np.linalg.norm(v),1e-7)
english=np.array([encode(p[1]) for p in test])
arabic=np.array([encode(p[2]) for p in test])
scores=arabic@english.T
order=np.argsort(-scores,axis=1,kind='stable')
correct=np.arange(len(test))
metrics=dict(training=len(train),heldOut=len(test),sourceGroupsTrain=len(set(group(p[0]) for p in train)),sourceGroupsTest=len(set(group(p[0]) for p in test)),eligible=len(test),vocabulary=len(vocab),dimensions=48,arabicToEnglishTop1=float((order[:,0]==correct).mean()),arabicToEnglishTop5=float((order[:,:5]==correct[:,None]).any(axis=1).mean()),meanCosineOnAlignedPairs=float(np.diag(scores).mean()),dataset='Parallel Universal Dependencies, English–Arabic. Unseen aligned sentences, not a student essay paraphrase benchmark.',dataSha256=hashlib.sha256((ROOT/'parallel.jsonl').read_bytes()).hexdigest())
def js(data): return json.dumps(data,ensure_ascii=False,separators=(',',':'))
syn=defaultdict(set)
for row in (ROOT/'arabic_synsets.tsv').read_text().splitlines():
    id,*lemmas=row.split('\t')
    for lemma in lemmas: syn[lemma].add(id)
# Only reasonably specific word senses contribute evidence.
awn={k:sorted(v) for k,v in sorted(syn.items()) if len(v)<=4}
out=ROOT.parent/'model.mjs'
data=base64.b64encode(quantized.tobytes()).decode()
out.write_text('// Generated by training/train.py. See NOTICE.md.\n'+
   'export const terms='+js(vocab)+';\nexport const dimensions=48;\nexport const bytes='+js(data)+';\nexport const senses='+js(awn)+';\nexport const stop='+js(sorted(STOP))+';\n')
(ROOT/'evaluation.json').write_text(json.dumps(metrics,indent=2,ensure_ascii=False)+'\n')
print(json.dumps(metrics,ensure_ascii=False))
